from __future__ import annotations

import glob
import os
import re
import shutil
import subprocess
from dataclasses import dataclass, field

import numpy as np

from pinneapple_simulation.numerical_solvers.lbm_tunnel import read_vtk

__all__ = ["fluidx3d_home", "fluidx3d_available", "WindTunnelSetup", "write_setup", "enable_features",
           "run_fluidx3d", "parse_forces", "read_results", "results_to_samples"]

MARK = "PINNEAPPLE_FORCE"


def fluidx3d_home() -> str | None:
    h = os.environ.get("FLUIDX3D_HOME")
    return h if h and os.path.isfile(os.path.join(h, "src", "setup.cpp")) else None


def fluidx3d_available() -> bool:
    """A checkout is configured and an OpenCL ICD is installed (FluidX3D still needs a working device)."""
    return fluidx3d_home() is not None and bool(glob.glob("/etc/OpenCL/vendors/*.icd"))


@dataclass
class WindTunnelSetup:
    """Wind tunnel around an STL body (or a sphere when ``stl`` is None), flow along +y (FluidX3D's convention in its
    examples). Lengths in metres, velocity in m/s; ``length_m`` is the body length along the flow (or the sphere
    diameter). ``box`` is the tunnel size relative to its x extent (aspect ratio passed to ``resolution``)."""
    length_m: float
    velocity_m_s: float
    nu_m2_s: float
    rho_kg_m3: float = 1.2
    stl: str | None = None
    box: tuple = (1.0, 2.0, 1.0)
    memory_mb: int = 1000
    body_cells: float | None = None          # body length in cells; default: a quarter of the box x size
    lbm_velocity: float = 0.075              # inflow speed in lattice units (Mach ~ 0.13)
    time_s: float = 1.0
    export_every_s: float = 0.1
    floor: bool = False                      # ground (moving with the flow, like a rolling road)
    rotation_deg: tuple = (0.0, 0.0, 0.0)    # body rotation about x, y, z
    subgrid: bool = True                     # Smagorinsky-Lilly LES
    fp16: bool = True                        # FP16S storage of the DDFs
    export: tuple = ("u", "rho", "flags")
    extra_defines: tuple = field(default_factory=tuple)

    def features(self) -> list[str]:
        f = ["EQUILIBRIUM_BOUNDARIES", "FORCE_FIELD", "VOLUME_FORCE"]
        if self.subgrid:
            f.append("SUBGRID")
        if self.floor:
            f.append("MOVING_BOUNDARIES")
        if self.fp16:
            f.append("FP16S")
        return f + list(self.extra_defines)

    def to_cpp(self) -> str:
        bx, by, bz = self.box
        body = f"{self.body_cells:.1f}f" if self.body_cells else "0.25f*(float)lbm_N.x"
        rx, ry, rz = self.rotation_deg
        stl = self.stl.replace("\\", "/") if self.stl else None
        geom = (f'\tlbm.voxelize_stl("{stl}", center, rotation, lbm_length, TYPE_S|TYPE_X);\n' if stl else
                "\tconst float R = 0.5f*lbm_length;\n")
        sphere = "" if stl else "\t\tif(sphere(x, y, z, center, R)) lbm.flags[n] = TYPE_S|TYPE_X;\n"
        floor = ("\t\tif(z==0u) { lbm.flags[n] = TYPE_S; lbm.u.y[n] = lbm_u; }\n" if self.floor else "")
        exports = "".join(f"\t\t\tlbm.{q}.write_device_to_vtk();\n" for q in self.export)
        return f"""// Generated by PINNeAPPle (pinneapple_simulation.external_solvers.fluidx3d); setup for the user's FluidX3D checkout.
// Required extensions (enabled in defines.hpp by enable_features): {", ".join(self.features())}
void main_setup() {{ // PINNeAPPle wind tunnel
\tconst uint3 lbm_N = resolution(float3({bx}f, {by}f, {bz}f), {int(self.memory_mb)}u);
\tconst float lbm_length = {body};
\tconst float lbm_u = {self.lbm_velocity}f;
\tconst float si_length = {self.length_m}f, si_u = {self.velocity_m_s}f, si_nu = {self.nu_m2_s}f, si_rho = {self.rho_kg_m3}f;
\tunits.set_m_kg_s(lbm_length, lbm_u, 1.0f, si_length, si_u, si_rho);
\tconst float lbm_nu = units.nu(si_nu);
\tconst ulong lbm_T = units.t({self.time_s}f), lbm_dt = max(1ull, (ulong)units.t({self.export_every_s}f));
\tLBM lbm(lbm_N, lbm_nu);
\tconst float3 center = float3(lbm.center().x, 0.35f*lbm.size().y, {"0.5f*lbm_length+1.0f" if self.floor else "lbm.center().z"});
\tconst float3x3 rotation = float3x3(float3(1, 0, 0), radians({rx}f))*float3x3(float3(0, 1, 0), radians({ry}f))*float3x3(float3(0, 0, 1), radians({rz}f));
{geom}\tconst uint Nx=lbm.get_Nx(), Ny=lbm.get_Ny(), Nz=lbm.get_Nz(); parallel_for(lbm.get_N(), [&](ulong n) {{ uint x=0u, y=0u, z=0u; lbm.coordinates(n, x, y, z);
{sphere}\t\tif(lbm.flags[n]!=(TYPE_S|TYPE_X)) lbm.u.y[n] = lbm_u;
\t\tif(x==0u||x==Nx-1u||y==0u||y==Ny-1u||z==Nz-1u{"" if self.floor else "||z==0u"}) lbm.flags[n] = TYPE_E;
{floor}\t}});
\tlbm.run(0u, lbm_T);
\twhile(lbm.get_t()<lbm_T) {{
\t\tlbm.run(lbm_dt, lbm_T);
\t\tlbm.update_force_field();
\t\tconst float3 F = lbm.object_force(TYPE_S|TYPE_X);
\t\tprint_info("{MARK} "+to_string(units.si_t(lbm.get_t()), 6u)+" "+to_string(units.si_F(F.x), 6u)+" "+to_string(units.si_F(F.y), 6u)+" "+to_string(units.si_F(F.z), 6u));
\t\tif(lbm.get_t()>=lbm_T) {{
{exports}\t\t}}
\t}}
}}
"""


def _home(home: str | None) -> str:
    h = home or fluidx3d_home()
    if h is None:
        raise RuntimeError("set FLUIDX3D_HOME to a FluidX3D checkout (https://github.com/ProjectPhysX/FluidX3D)")
    return h


def write_setup(setup: WindTunnelSetup, home: str | None = None) -> str:
    """Replace the active ``main_setup()`` of ``src/setup.cpp`` by the generated one: the original file is kept as
    ``setup.cpp.pinneapple.bak`` and only the generated function is compiled (the file's other setups stay commented
    out as FluidX3D ships them)."""
    h = _home(home)
    path = os.path.join(h, "src", "setup.cpp")
    bak = path + ".pinneapple.bak"
    if not os.path.exists(bak):
        shutil.copy(path, bak)
    src = open(bak).read()
    head = src[:src.index("void main_setup()")] if "void main_setup()" in src else '#include "setup.hpp"\n\n'
    # the shipped file keeps every setup inside /* ... */ except one; we drop all of them and append ours
    head = re.sub(r"/\*void main_setup\(\).*", "", head, flags=re.S)
    with open(path, "w") as fh:
        fh.write(head.rstrip() + "\n\n" + setup.to_cpp())
    return path


def enable_features(features, home: str | None = None) -> str:
    """Uncomment ``#define <feature>`` lines in ``src/defines.hpp`` (backup ``defines.hpp.pinneapple.bak``) and comment
    out ``BENCHMARK``, which would otherwise run the benchmark instead of the setup."""
    h = _home(home)
    path = os.path.join(h, "src", "defines.hpp")
    bak = path + ".pinneapple.bak"
    if not os.path.exists(bak):
        shutil.copy(path, bak)
    t = open(bak).read()
    for feat in features:
        t = re.sub(rf"^//\s*#define {feat}\b", f"#define {feat}", t, flags=re.M)
    t = re.sub(r"^#define BENCHMARK\b", "//#define BENCHMARK", t, flags=re.M)
    with open(path, "w") as fh:
        fh.write(t)
    return path


def run_fluidx3d(setup: WindTunnelSetup | None = None, home: str | None = None, device: str | None = None,
                 timeout: float = 24 * 3600, log: str = "log.pinneapple") -> subprocess.CompletedProcess:
    """Write the setup and the defines (when ``setup`` is given), then compile and run with ``make.sh``.
    Output goes to ``<home>/<log>``; raises RuntimeError on a non-zero exit."""
    h = _home(home)
    if setup is not None:
        write_setup(setup, h)
        enable_features(setup.features(), h)
    cmd = ["bash", "make.sh"] + ([str(device)] if device is not None else [])
    with open(os.path.join(h, log), "w") as fh:
        r = subprocess.run(cmd, cwd=h, stdout=fh, stderr=subprocess.STDOUT, timeout=timeout, check=False)
    if r.returncode:
        raise RuntimeError(f"FluidX3D exited with {r.returncode}; see {os.path.join(h, log)}")
    return r


def parse_forces(text: str) -> np.ndarray:
    """Rows (t [s], Fx, Fy, Fz [N]) printed by the generated setup."""
    rows = re.findall(rf"{MARK}\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)", text)
    return np.array(rows, dtype=float).reshape(-1, 4)


def read_results(home: str | None = None, log: str = "log.pinneapple", export_dir: str | None = None) -> dict:
    """Force history from the log and the last exported field of each quantity (``bin/export/<q>-<step>.vtk``)."""
    h = _home(home) if export_dir is None else None
    out: dict = {"forces": np.zeros((0, 4)), "fields": {}}
    if h is not None and os.path.exists(os.path.join(h, log)):
        out["forces"] = parse_forces(open(os.path.join(h, log), errors="replace").read())
    d = export_dir or os.path.join(h, "bin", "export")
    for f in sorted(glob.glob(os.path.join(d, "*.vtk"))):
        m = re.match(r"(.+?)-(\d+)\.vtk$", os.path.basename(f))
        if not m:
            continue
        q, step = m.group(1), int(m.group(2))
        if q not in out["fields"] or step >= out["fields"][q]["step"]:
            out["fields"][q] = {"step": step, "path": f}
    for v in out["fields"].values():
        v.update(read_vtk(v["path"]))
    return out


def results_to_samples(results: dict, source: str = "fluidx3d") -> list:
    """One PhysicalSample with the last exported fields on their regular grid (positions from origin/spacing)."""
    import torch

    from pinneapple_data.physical_sample import PhysicalSample

    fields = results["fields"]
    if not fields:
        return []
    ref = next(iter(fields.values()))
    nx, ny, nz = ref["dimensions"]
    o, s = np.asarray(ref["origin"]), np.asarray(ref["spacing"])
    axes = [o[i] + s[i] * np.arange(n) for i, n in enumerate((nx, ny, nz))]
    state = {q: torch.as_tensor(np.asarray(v["data"], np.float32)) for q, v in fields.items()}
    return [PhysicalSample(state=state, domain={"type": "grid", "coords": {k: torch.as_tensor(a) for k, a in
                                                                          zip("xyz", axes, strict=True)}},
                           provenance={"version": "0.1", "source": source, "step": ref["step"]},
                           schema={"units": {"u": "m/s", "rho": "kg/m^3"}})]
