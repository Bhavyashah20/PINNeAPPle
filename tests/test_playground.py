"""PINNeAPPle Playground (apps/playground): the ONNX files the browser runs reproduce the zoo's PyTorch models to
1e-5 on the zoo test sets, and the page's committed metadata and fixtures are not stale."""
from __future__ import annotations

import hashlib
import importlib.util
import json
import warnings
from pathlib import Path

import numpy as np
import pytest

torch = pytest.importorskip("torch")
pytest.importorskip("onnx")
pytest.importorskip("onnxruntime")

from pinneapple_hub import zoo  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "apps" / "playground"
MODELS = ["airfoil_cst_rans_mlp", "heatsink_forced_mlp", "rover_contact_grc1_viper"]
TOL = 1e-5


def _load_build_assets():
    spec = importlib.util.spec_from_file_location("playground_build_assets", APP / "tools" / "build_assets.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


ba = _load_build_assets()


@pytest.fixture(scope="module", params=MODELS)
def model(request):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return request.param, zoo.load(request.param, offline=True)


def _parity(name, zm, data: bytes) -> float:
    X = ba.parity_inputs(name, zm)
    ref, got = ba.onnx_outputs(name, zm, X), ba.run_onnx(data, X)
    sc = ba.output_scale(name, zm)
    assert set(ref) == set(got)
    return max(ba.parity_error(ref[k], got[k], sc[k], ref["mean"] if k == "std" else None) for k in ref)


def test_committed_onnx_matches_pytorch_on_the_zoo_test_sets(model):
    name, zm = model
    data = (APP / "site" / "models" / f"{name}.onnx").read_bytes()
    assert _parity(name, zm, data) <= TOL


def test_fresh_export_matches_pytorch(model):
    name, zm = model
    assert _parity(name, zm, ba.export_onnx(name, zm)) <= TOL


def test_page_metadata_is_current(model):
    name, zm = model
    meta = json.loads((APP / "site" / "models" / f"{name}.json").read_text())
    data = (APP / "site" / "models" / f"{name}.onnx").read_bytes()
    assert meta["onnx"]["sha256"] == hashlib.sha256(data).hexdigest()
    assert meta["onnx"]["inputs"] == zm.input_names
    card = zm.card.to_dict()
    assert meta["card"]["version"] == card["version"]
    assert meta["card"]["validity_range"] == json.loads(json.dumps(card["validity_range"]))
    for k, v in card["validation_metrics"].items():
        assert meta["card"]["validation_metrics"][k] == pytest.approx(v, rel=1e-5)
    assert meta["card"]["trust_report"]["decisao"] == card["trust_report"]["decisao"]


def test_smoke_fixtures_are_the_zoo_predictions():
    smoke = json.loads((APP / "tests" / "fixtures" / "smoke.json").read_text())
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        a = zoo.load("airfoil_cst_rans_mlp", offline=True)
        for c in smoke["airfoil"]:
            p = a._forward(np.array([[*c["shape"], c["alpha"]]]))
            assert p["Cl"][0] == pytest.approx(c["Cl"], abs=1e-6)          # float32 network, rounded inputs
            assert bool(a.in_range([[*c["shape"], c["alpha"]]])[0]) == c["in_range"]
        r = zoo.load("rover_contact_grc1_viper", offline=True)
        for c in smoke["rover"]:
            assert r._forward(np.array([[c["slip"], c["sinkage_m"]]]))["Fx_N"][0] == pytest.approx(c["Fx_N"], abs=1e-6)


def test_js_fixtures_match_the_python_geometry():
    from pinneapple_design.aero import geometry as g
    fx = json.loads((APP / "tests" / "fixtures" / "geometry.json").read_text())
    for c in fx["cases"]:
        yu, yl = g.surfaces(np.array(c["shape"]), np.array(c["x"]))
        np.testing.assert_allclose(yu, c["upper"], atol=1e-11)
        np.testing.assert_allclose(yl, c["lower"], atol=1e-11)
    for code, w in fx["naca4"].items():
        np.testing.assert_allclose(g.naca4(code), w, atol=1e-11)


def test_gallery_lists_every_geometry():
    from pinneapple_design import geometry_library as gl
    idx = json.loads((APP / "site" / "data" / "geometries.json").read_text())
    names = [x["name"] for x in idx["geometries"]]
    assert names == gl.list()
    for n in names:
        assert (APP / "site" / "data" / "thumbs" / f"{n}.jpg").exists()


def test_static_build_is_self_contained(tmp_path):
    spec = importlib.util.spec_from_file_location("playground_build", APP / "build.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    info = mod.build(tmp_path / "site")
    out = Path(info["out"])
    assert (out / "vendor" / "three" / "three.module.min.js").exists()
    assert "__PRECACHE__" not in (out / "sw.js").read_text()
    assert info["first_load_bytes"] < 1_000_000          # < 3 s on a normal connection
    html = (out / "index.html").read_text()
    for bad in ("http://", "Generated by"):
        assert bad not in html
